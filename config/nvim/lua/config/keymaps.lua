local map = vim.keymap.set

map("n", "<Esc>", "<cmd>nohlsearch<cr>")
map({ "n", "i", "x" }, "<C-s>", "<cmd>w<cr><esc>", { desc = "save" })
map("n", "<C-h>", "<C-w>h")
map("n", "<C-j>", "<C-w>j")
map("n", "<C-k>", "<C-w>k")
map("n", "<C-l>", "<C-w>l")
map("n", "<S-h>", "<cmd>bprevious<cr>", { desc = "prev buffer" })
map("n", "<S-l>", "<cmd>bnext<cr>", { desc = "next buffer" })
map("n", "<leader>bd", function() Snacks.bufdelete() end, { desc = "delete buffer" })
map("x", "<", "<gv")
map("x", ">", ">gv")
map("x", "J", ":m '>+1<cr>gv=gv", { silent = true })
map("x", "K", ":m '<-2<cr>gv=gv", { silent = true })

map("n", "<leader><space>", function() Snacks.picker.smart() end, { desc = "smart find" })
map("n", "<leader>ff", function() Snacks.picker.files() end, { desc = "files" })
map("n", "<leader>fg", function() Snacks.picker.grep() end, { desc = "grep" })
map("n", "<leader>fb", function() Snacks.picker.buffers() end, { desc = "buffers" })
map("n", "<leader>fr", function() Snacks.picker.recent() end, { desc = "recent" })
map("n", "<leader>fh", function() Snacks.picker.help() end, { desc = "help" })
map("n", "<leader>fk", function() Snacks.picker.keymaps() end, { desc = "keymaps" })
map("n", "<leader>fd", function() Snacks.picker.diagnostics() end, { desc = "diagnostics" })
map({ "n", "x" }, "<leader>fw", function() Snacks.picker.grep_word() end, { desc = "grep word" })
map("n", "<leader>e", function() Snacks.explorer() end, { desc = "explorer" })

map("n", "<leader>gg", function() Snacks.lazygit() end, { desc = "lazygit" })
map("n", "<leader>gb", "<cmd>Gitsigns blame_line<cr>", { desc = "blame line" })
map("n", "<leader>gB", "<cmd>Gitsigns toggle_current_line_blame<cr>", { desc = "toggle inline blame" })
map("n", "<leader>gp", "<cmd>Gitsigns preview_hunk<cr>", { desc = "preview hunk" })
map("n", "<leader>gr", "<cmd>Gitsigns reset_hunk<cr>", { desc = "reset hunk" })
map("n", "]h", "<cmd>Gitsigns next_hunk<cr>", { desc = "next hunk" })
map("n", "[h", "<cmd>Gitsigns prev_hunk<cr>", { desc = "prev hunk" })

map({ "n", "x" }, "<leader>cf", function() require("conform").format() end, { desc = "format" })
map("n", "<leader>cd", vim.diagnostic.open_float, { desc = "line diagnostics" })

map("n", "<leader>ut", function() require("meloworld").toggle() end, { desc = "toggle pastel/black theme" })
map("n", "<leader>un", function() Snacks.notifier.show_history() end, { desc = "notifications" })
map("n", "<leader>uw", "<cmd>set wrap!<cr>", { desc = "toggle wrap" })
map({ "n", "t" }, "<C-/>", function() Snacks.terminal() end, { desc = "terminal" })
