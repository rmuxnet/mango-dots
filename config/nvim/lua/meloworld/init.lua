local M = {}

local state_file = vim.fn.stdpath("state") .. "/meloworld_variant"

function M.saved_variant()
  local f = io.open(state_file, "r")
  if not f then
    return (vim.env.TERM or ""):match("^foot") and "black" or "pastel"
  end
  local v = f:read("*l")
  f:close()
  return (v == "black" or v == "pastel") and v or "pastel"
end

local function save_variant(v)
  local f = io.open(state_file, "w")
  if f then
    f:write(v)
    f:close()
  end
end

