local function terminal_colors(c)
  local list = {
    "#212121", c.red, c.green, c.yellow, c.blue, c.purple, c.cyan, "#ffffff",
    "#616161", c.red_hot, "#69f0ae", "#ffff00", "#448aff", c.magenta, "#64ffda", "#ffffff",
  }
  for i, v in ipairs(list) do
    vim.g["terminal_color_" .. (i - 1)] = v
  end
end

function M.load(variant)
  variant = variant or M.saved_variant()
  M.variant = variant
  local c = require("meloworld.palette").get(variant)
  if vim.g.colors_name then
    vim.cmd("hi clear")
  end
  vim.o.termguicolors = true
  vim.o.background = "dark"
  vim.g.colors_name = "meloworld"
  for name, spec in pairs(groups(c)) do
    vim.api.nvim_set_hl(0, name, spec)
  end
  terminal_colors(c)
  M.colors = c
  vim.api.nvim_exec_autocmds("User", { pattern = "MeloworldChanged", modeline = false })
end

function M.toggle()
  local next_variant = (M.variant == "black") and "pastel" or "black"
  save_variant(next_variant)
  M.load(next_variant)
  vim.notify("theme: " .. next_variant, vim.log.levels.INFO, { title = "meloworld" })
end

